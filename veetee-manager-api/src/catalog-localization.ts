const ragFlowRemark = 'Tích hợp kho kiến thức RAGFlow tùy chọn. Hãy cung cấp Base URL và API key của dịch vụ trước khi bật.'

function normalizeLegacyPresentation(value: string): string {
  const punctuation = value.replace(/[\u3000-\u303f]/gu, (character) => {
    switch (character.codePointAt(0)) {
      case 0x3001: return ', '
      case 0x3002: return '. '
      case 0xff0c: return ', '
      case 0xff1a: return ': '
      case 0xff1b: return '; '
      case 0xff08: return '('
      case 0xff09: return ')'
      default: return ' '
    }
  })
  return punctuation.replace(/[ \t]{2,}/gu, ' ').trim()
}

export function localizeLegacyCatalogText(value: string): string {
  if (!/[\u3400-\u9fff]/u.test(value)) return value
  if (value.startsWith('RAGFlow\u{914d}\u{7f6e}\u{8bf4}\u{660e}')) return ragFlowRemark
  const exact = exactReplacements.get(value)
  if (exact) return exact
  let next = value
  // Match the most specific phrase first.  This keeps labels such as
  // "model directory" intact instead of applying the shorter "model"
  // replacement before the full phrase.
  for (const [from, to] of [...replacements].sort((a, b) => b[0].length - a[0].length)) next = next.replaceAll(from, to)
  // A legacy label can contain a new phrase that is not in the table.  Never
  // leak CJK into the Vietnamese Manager surface; keep surrounding technical
  // identifiers and punctuation intact.
  return normalizeLegacyPresentation(next.replace(/[\u3400-\u9fff]/gu, ''))
}

export function localizeLegacyCatalogValue<T>(value: T): T {
  if (typeof value === 'string') return localizeLegacyCatalogText(value) as T
  if (Array.isArray(value)) return value.map((item) => localizeLegacyCatalogValue(item)) as T
  if (value && typeof value === 'object') {
    const output: Record<string, unknown> = {}
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) output[key] = localizeLegacyCatalogValue(item)
    return output as T
  }
  return value
}
